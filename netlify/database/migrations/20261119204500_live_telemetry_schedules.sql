ALTER TABLE user_settings
  ADD COLUMN IF NOT EXISTS tank_level_pct INTEGER NOT NULL DEFAULT 85,
  ADD COLUMN IF NOT EXISTS tank_capacity_liters INTEGER NOT NULL DEFAULT 2000,
  ADD COLUMN IF NOT EXISTS water_used_liters INTEGER NOT NULL DEFAULT 320,
  ADD COLUMN IF NOT EXISTS water_saved_liters INTEGER NOT NULL DEFAULT 1450,
  ADD COLUMN IF NOT EXISTS energy_kwh DOUBLE PRECISION NOT NULL DEFAULT 22.1,
  ADD COLUMN IF NOT EXISTS tariff_per_kwh INTEGER NOT NULL DEFAULT 1445;

CREATE TABLE IF NOT EXISTS schedules (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label TEXT NOT NULL,
  plot_target TEXT NOT NULL DEFAULT 'Semua Petak',
  time_wib TEXT NOT NULL,
  duration_min INTEGER NOT NULL DEFAULT 15,
  skip_on_rain BOOLEAN NOT NULL DEFAULT TRUE,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS moisture_history (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day_date TEXT NOT NULL,
  series_a INTEGER NOT NULL,
  series_b INTEGER NOT NULL,
  UNIQUE (user_id, day_date)
);
